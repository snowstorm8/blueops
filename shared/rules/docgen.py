"""Generate the rule-library reference (``docs/detection-library.md``) from the rule packs.

The documentation is generated so it cannot drift from the rules; a test fails when the
checked-in file differs from this output.
"""

from __future__ import annotations

from shared.rules.loader import RuleSet
from shared.rules.model import Rule
from shared.rules.render_util import md_code, md_text


def _expr(e: object) -> str:
    if isinstance(e, str):
        return e
    ((k, v),) = e.items()  # type: ignore[union-attr]
    return f"not {_expr(v)}" if k == "not" else "(" + f" {k} ".join(_expr(x) for x in v) + ")"


def rule_section(r: Rule) -> list[str]:
    out = [
        f"### {r.id} - {md_text(r.name)}",
        "",
        f"{md_text(r.description)}",
        "",
        "| | |",
        "|---|---|",
        f"| Version | {r.version} (pack `{r.pack}`) |",
        f"| Platforms | {', '.join(r.platforms)} |",
        f"| Category | {r.category} |",
        f"| Nature | {r.nature} |",
        f"| Severity | {r.severity}: {md_text(r.severity_reason)} |",
        f"| Confidence | {r.confidence}: {md_text(r.confidence_reason)} |",
        f"| Enabled by default | {'yes' if r.enabled else 'no'} |",
        f"| Needs coverage | {', '.join(md_code(c) for c in r.requires_coverage) or 'none'} |",
        "",
        f"**Why it matters.** {md_text(r.rationale)}",
        "",
        "**Conditions.**",
        "",
    ]
    for c in r.clauses:
        flags = []
        if c.optional:
            flags.append("optional")
        if c.min_matches > 1:
            flags.append(f"at least {c.min_matches} matches")
        if c.distinct:
            flags.append(f"at least {c.distinct[1]} distinct `{c.distinct[0]}` values")
        extra = f" ({'; '.join(flags)})" if flags else ""
        out.append(f"- `{c.id}` on `{c.source}`{extra}: {md_text(c.description)}  ")
        out.append(f"  `{c.where.text}`")
    out += [
        "",
        f"Requires: `{_expr(r.require)}`."
        + (f" Items are grouped by `{r.join_on}`." if r.join_on else ""),
    ]
    for a in r.severity_rules:
        out.append(f"Severity becomes **{a.value}** when `{_expr(a.when)}`: {md_text(a.reason)}")
    for a in r.confidence_rules:
        out.append(f"Confidence becomes **{a.value}** when `{_expr(a.when)}`: {md_text(a.reason)}")
    if r.false_positives:
        out += ["", "**Possible benign causes.**", ""] + [
            f"- {md_text(x)}" for x in r.false_positives
        ]
    if r.confidence_boosters:
        out += ["", "**Would raise confidence.**", ""] + [
            f"- {md_text(x)}" for x in r.confidence_boosters
        ]
    out += ["", "**Investigate.**", ""] + [
        f"{i}. {md_text(x)}" for i, x in enumerate(r.investigation, 1)
    ]
    out += ["", f"**Remediation.** {md_text(r.remediation)}", ""]
    attack = r.references.get("attack", [])
    nist = r.references.get("nist", [])
    if attack or nist:
        out.append("**References.**")
        out.append("")
        for a in attack:
            out.append(
                f"- ATT&CK [{a['id']}](https://attack.mitre.org/techniques/{a['id'].replace('.', '/')}/) ({a['relationship']}): {md_text(a['explanation'])}"
            )
        if nist:
            out.append(f"- NIST SP 800-53 Rev. 5: {', '.join(nist)}")
        out.append("")
    out += ["**Examples (executed by `rules test`).**", ""]
    out += [f"- `{e['expect']}`: {md_text(e['name'])}" for e in r.examples]
    out.append("")
    return out


def render_library(rs: RuleSet) -> str:
    rules = rs.ordered()
    lines = [
        "# Detection rule library",
        "",
        "Generated by `python -m shared.engine rules docs` from `shared/rules/library/*.json`; do not edit by hand.",
        "A test fails if this file is out of date. Each rule below also ships executable examples.",
        "",
        "| Rule | Name | Platforms | Severity | Confidence | Nature |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| [{r.id}](#{r.id.lower()}---{_anchor(r.name)}) | {md_text(r.name)} | {', '.join(r.platforms)} | {r.severity} | {r.confidence} | {r.nature} |"
        for r in rules
    ]
    lines.append("")
    for r in rules:
        lines += rule_section(r)
    return "\n".join(lines).rstrip() + "\n"


def _anchor(name: str) -> str:
    import re  # noqa: PLC0415 - tiny helper, import kept local

    return re.sub(r"[^a-z0-9 -]", "", name.lower()).strip().replace(" ", "-")
